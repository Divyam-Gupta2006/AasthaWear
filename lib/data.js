export const bySlug = (s) => {
  if (!s) return null;
  const clean = s.toLowerCase().trim();
  return products.find((p) => p.slug === clean || (p.aliases && p.aliases.includes(clean)));
};

export const inr = (n) => {
  if (typeof n !== 'number') return '₹0';
  return '₹' + n.toLocaleString('en-IN');
};

